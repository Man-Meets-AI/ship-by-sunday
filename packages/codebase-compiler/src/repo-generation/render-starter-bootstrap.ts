import type { RenderedCodebaseFile } from "../codebases/render-types";
import type { CanonicalProjectDefinition } from "../canonical-project-definition/project-definition";

const BUN_INSTALL_DOCS_URL = "https://bun.sh/docs/installation";
const CLERK_SIGN_UP_URL = "https://dashboard.clerk.com/sign-up";
const CONVEX_DASHBOARD_URL = "https://dashboard.convex.dev";
const STRIPE_REGISTER_URL = "https://dashboard.stripe.com/register";

function shellQuote(value: string) {
	return `'${value.replace(/'/g, "'\\''")}'`;
}

function renderStarterBootstrapContent(productName: string) {
	return [
		"#!/usr/bin/env bash",
		"set -euo pipefail",
		"",
		'SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"',
		'cd "$SCRIPT_DIR"',
		"",
		`PRODUCT_NAME=${shellQuote(productName)}`,
		'ENV_EXAMPLE_PATH="apps/web/.env.local.example"',
		'ENV_FILE_PATH="apps/web/.env.local"',
		'DESIGN_SYSTEM_FACTS_PATH="docs/facts/design-system.json"',
		`BUN_INSTALL_DOCS_URL=${shellQuote(BUN_INSTALL_DOCS_URL)}`,
		`CLERK_SIGN_UP_URL=${shellQuote(CLERK_SIGN_UP_URL)}`,
		`CONVEX_DASHBOARD_URL=${shellQuote(CONVEX_DASHBOARD_URL)}`,
		`STRIPE_REGISTER_URL=${shellQuote(STRIPE_REGISTER_URL)}`,
		"",
		"step() {",
		"  printf '\\n==> %s\\n' \"$1\"",
		"}",
		"",
		"note() {",
		"  printf '    %s\\n' \"$1\"",
		"}",
		"",
		"warn() {",
		"  printf '\\n[warn] %s\\n' \"$1\"",
		"}",
		"",
		"prompt_yes_no() {",
		"  local prompt=$1",
		"  local default_answer=$2",
		"  local prompt_suffix='[y/N]'",
		"  local reply=''",
		"",
		'  if [ "$default_answer" = "Y" ]; then',
		"    prompt_suffix='[Y/n]'",
		"  fi",
		"",
		'  read -r -p "$prompt $prompt_suffix " reply || true',
		"",
		'  if [ -z "$reply" ]; then',
		"    reply=$default_answer",
		"  fi",
		"",
		'  case "$reply" in',
		"    [Yy]*) return 0 ;;",
		"    *) return 1 ;;",
		"  esac",
		"}",
		"",
		"open_url() {",
		"  local url=$1",
		"",
		"  if command -v open >/dev/null 2>&1; then",
		'    open "$url" >/dev/null 2>&1 || true',
		"    return 0",
		"  fi",
		"",
		"  if command -v xdg-open >/dev/null 2>&1; then",
		'    xdg-open "$url" >/dev/null 2>&1 || true',
		"    return 0",
		"  fi",
		"",
		"  if command -v cmd.exe >/dev/null 2>&1; then",
		'    cmd.exe /c start "" "$url" >/dev/null 2>&1 || true',
		"    return 0",
		"  fi",
		"",
		'  note "Open this URL manually: $url"',
		"}",
		"",
		"ensure_bun() {",
		"  if command -v bun >/dev/null 2>&1; then",
		'    note "Using Bun $(bun --version)"',
		"    return 0",
		"  fi",
		"",
		'  warn "Bun is required before this Codebase can install dependencies."',
		'  note "Install Bun, then rerun this script: $BUN_INSTALL_DOCS_URL"',
		'  if prompt_yes_no "Open the Bun installation guide now?" "Y"; then',
		'    open_url "$BUN_INSTALL_DOCS_URL"',
		"  fi",
		"  exit 1",
		"}",
		"",
		"install_dependencies() {",
		'  step "Installing workspace dependencies"',
		"  bun install",
		"}",
		"",
		"ensure_local_env_file() {",
		'  if [ -f "$ENV_FILE_PATH" ]; then',
		'    note "Keeping existing $ENV_FILE_PATH"',
		"    return 0",
		"  fi",
		"",
		'  if [ ! -f "$ENV_EXAMPLE_PATH" ]; then',
		'    warn "Missing $ENV_EXAMPLE_PATH, so the local env file was not created."',
		"    return 0",
		"  fi",
		"",
		'  step "Creating local env file"',
		'  cp "$ENV_EXAMPLE_PATH" "$ENV_FILE_PATH"',
		'  note "Created $ENV_FILE_PATH from the tracked example."',
		"}",
		"",
		"read_preset_code() {",
		'  if [ ! -f "$DESIGN_SYSTEM_FACTS_PATH" ]; then',
		"    return 0",
		"  fi",
		"",
		"  if command -v node >/dev/null 2>&1; then",
		'    node -e \'const fs = require("node:fs"); const filePath = process.argv[1]; const json = JSON.parse(fs.readFileSync(filePath, "utf8")); process.stdout.write(json?.preset?.presetCode ?? "");\' "$DESIGN_SYSTEM_FACTS_PATH"',
		"    return 0",
		"  fi",
		"",
		'  sed -n \'s/.*"presetCode":[[:space:]]*"\\([^"]*\\)".*/\\1/p\' "$DESIGN_SYSTEM_FACTS_PATH" | head -n 1',
		"}",
		"",
		"apply_shadcn_preset() {",
		"  local preset_code",
		"  preset_code=$(read_preset_code || true)",
		"",
		'  if [ -z "$preset_code" ]; then',
		'    warn "No shadcn preset code was found in $DESIGN_SYSTEM_FACTS_PATH."',
		"    return 0",
		"  fi",
		"",
		'  if [[ ! "$preset_code" =~ ^[a-z0-9][a-z0-9-]{0,80}$ ]]; then',
		'    warn "Skipping shadcn preset apply because the generated preset code is invalid."',
		"    return 0",
		"  fi",
		"",
		"  if ! command -v npx >/dev/null 2>&1; then",
		'    warn "Skipping shadcn preset apply because npx is unavailable on this machine."',
		'    note "After installing Node.js, run: (cd apps/web && npx --yes shadcn@latest apply --preset $preset_code -y)"',
		"    return 0",
		"  fi",
		"",
		'  if ! prompt_yes_no "Apply the shadcn preset ($preset_code) to apps/web now?" "Y"; then',
		'    note "Skipped shadcn preset application."',
		"    return 0",
		"  fi",
		"",
		'  step "Applying shadcn preset $preset_code"',
		'  (cd apps/web && npx --yes shadcn@latest apply --preset "$preset_code" -y)',
		"}",
		"",
		"open_provider_setup_pages() {",
		'  if prompt_yes_no "Open Clerk, Convex, and Stripe setup pages now?" "Y"; then',
		'    step "Opening provider setup pages"',
		'    note "Clerk:  $CLERK_SIGN_UP_URL"',
		'    open_url "$CLERK_SIGN_UP_URL"',
		'    note "Convex: $CONVEX_DASHBOARD_URL"',
		'    open_url "$CONVEX_DASHBOARD_URL"',
		'    note "Stripe: $STRIPE_REGISTER_URL"',
		'    open_url "$STRIPE_REGISTER_URL"',
		"    return 0",
		"  fi",
		"",
		'  note "Provider setup pages skipped. Manual links:"',
		'  note "Clerk:  $CLERK_SIGN_UP_URL"',
		'  note "Convex: $CONVEX_DASHBOARD_URL"',
		'  note "Stripe: $STRIPE_REGISTER_URL"',
		"}",
		"",
		"print_next_steps() {",
		'  step "Next steps"',
		'  note "1. Run bun run codex:skills:install."',
		'  note "2. Restart Codex if the new skills do not appear."',
		'  note "3. If you use Linear, run \\$starter-linear-workflow before implementation."',
		'  note "4. Follow START-HERE.md in order: \\$starter-core-setup, then \\$starter-auth-setup, then \\$starter-billing-setup."',
		'  note "5. Fill in apps/web/.env.local with your provider values."',
		'  note "6. Start the generated template app with bun run dev."',
		"}",
		"",
		"main() {",
		"  printf '\\nWelcome to %s.\\n' \"$PRODUCT_NAME\"",
		'  note "This bootstrap installs dependencies, prepares your local env file, opens provider setup pages, and can apply the shipped shadcn preset."',
		"",
		"  ensure_bun",
		"  install_dependencies",
		"  ensure_local_env_file",
		"  open_provider_setup_pages",
		"  apply_shadcn_preset",
		"  print_next_steps",
		"}",
		"",
		'main "$@"',
	].join("\n");
}

export function renderStarterBootstrapFile(
	projectDefinition: CanonicalProjectDefinition,
): RenderedCodebaseFile {
	return {
		path: "bootstrap.sh",
		content: renderStarterBootstrapContent(
			projectDefinition.facts.product_name,
		),
	};
}
